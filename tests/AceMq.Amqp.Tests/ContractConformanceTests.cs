    [Fact]
    public void TheThresholdTableIsTheStatedRuleRecomputed()
    {
        // The fixture states the rule in prose and then tabulates it. Recomputing the
        // table from the prose catches a generator that tabulated something else —
        // the one thing comparing two implementations to each other cannot catch,
        // because they would both be compared to the same wrong table.
        var fixture = Section("brokerWaitThreshold");
        var rule = fixture.GetProperty("rule").GetString()!;
        Assert.Contains("at or above the threshold", rule);
        Assert.Contains("threshold of zero sends nothing to the broker", rule);

        foreach (var row in fixture.GetProperty("cases").EnumerateArray())
        {
            var threshold = row.GetProperty("thresholdMillis").GetInt64();
            var delay = row.GetProperty("delayMillis").GetInt64();

            var byTheRule = threshold > 0 && delay > 0 && delay >= threshold;

            Assert.Equal(byTheRule, row.GetProperty("waitsInBroker").GetBoolean());
        }
    }

