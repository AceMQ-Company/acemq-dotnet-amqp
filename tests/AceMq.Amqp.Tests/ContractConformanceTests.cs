    /// <summary>
    /// The declarations this library makes, from both halves of the topology.
    /// </summary>
    /// <remarks>
    /// Neither half is the whole thing, which is why the fixture records a
    /// <c>declaredBy</c> against every entry. The application declares its exchange,
    /// its queue and its binding; the consumer declares the rungs it will publish
    /// retries into. A test that looked at only one of them would find half a
    /// topology and call it correct.
    /// </remarks>
    private static async Task<Recorder> DeclaredByBothHalvesAsync()
    {
        var recorder = new Recorder();

        // The application's half, the same shape the fixture's generator builds:
        // exchange, queue with dead-lettering, binding.
        var declared = Topology.Define()
            .Exchange("orders", "topic")
            .QueueWithDeadLetter(Queue)
            .Bind(Queue, "orders", "order.*")
            .Build();

        foreach (var exchange in declared.Exchanges)
        {
            recorder.Exchange(exchange.Name, exchange.Type, exchange.Durable, "topology");
        }
        foreach (var queue in declared.Queues)
        {
            recorder.Queue(queue.Name, queue.Type, queue.Durable, queue.Arguments, "topology");
        }
        foreach (var binding in declared.Bindings)
        {
            recorder.Binding(binding.Queue, binding.Exchange, binding.RoutingKey, "topology");
        }

        // The consumer's half, which is literally what ConsumeAsync runs before it
        // subscribes.
        recorder.By = "consumer";
        await RetryLadder.For(Queue, TopologyPolicy()).DeclareAsync(recorder, CancellationToken.None);

        return recorder;
    }

    [Fact]
    public async Task TheDeclaredTopologyIsTheOneTheFixtureRecords()
    {
        var fixture = Section("topology");
        var recorder = await DeclaredByBothHalvesAsync();

        // Exchanges: name, type, durability.
        var exchanges = new List<string>();
        foreach (var e in fixture.GetProperty("exchanges").EnumerateArray())
        {
            var name = e.GetProperty("name").GetString()!;
            exchanges.Add(name);
            Assert.True(recorder.Exchanges.ContainsKey(name), $"nothing declared the exchange {name}");
            var actual = recorder.Exchanges[name];
            Assert.Equal(e.GetProperty("type").GetString(), actual.Type);
            Assert.Equal(e.GetProperty("durable").GetBoolean(), actual.Durable);
        }
        Assert.Equal(exchanges.OrderBy(n => n, StringComparer.Ordinal),
            recorder.Exchanges.Keys.OrderBy(n => n, StringComparer.Ordinal));

        // Queues: name, type, durability and the exact argument table.
        var queues = new List<string>();
        foreach (var q in fixture.GetProperty("queues").EnumerateArray())
        {
            var name = q.GetProperty("name").GetString()!;
            queues.Add(name);
            Assert.True(recorder.Queues.ContainsKey(name), $"nothing declared the queue {name}");
            var actual = recorder.Queues[name];

            Assert.Equal(
                q.GetProperty("type").GetString(),
                actual.Type.ToString().ToLowerInvariant());
            Assert.Equal(q.GetProperty("durable").GetBoolean(), actual.Durable);

            var expectedArgs = q.GetProperty("arguments").EnumerateObject()
                .ToDictionary(p => p.Name, p => Scalar(p.Value), StringComparer.Ordinal);
            var actualArgs = actual.Arguments.ToDictionary(
                p => p.Key,
                p => Convert.ToString(p.Value, CultureInfo.InvariantCulture)!,
                StringComparer.Ordinal);

            Assert.Equal(
                expectedArgs.OrderBy(p => p.Key, StringComparer.Ordinal),
                actualArgs.OrderBy(p => p.Key, StringComparer.Ordinal));
        }
        Assert.Equal(queues.OrderBy(n => n, StringComparer.Ordinal),
            recorder.Queues.Keys.OrderBy(n => n, StringComparer.Ordinal));

        // Bindings: queue, exchange and routing key, as a set.
        var bindings = fixture.GetProperty("bindings").EnumerateArray()
            .Select(b => Key(
                b.GetProperty("queue").GetString()!,
                b.GetProperty("exchange").GetString()!,
                b.GetProperty("routingKey").GetString()!))
            .OrderBy(k => k, StringComparer.Ordinal)
            .ToArray();

        Assert.Equal(bindings, recorder.Bindings.Keys.OrderBy(k => k, StringComparer.Ordinal));
    }

    [Fact]
    public async Task EachHalfOfTheTopologyDeclaresWhatTheFixtureSaysItDoes()
    {
        var fixture = Section("topology");
        var recorder = await DeclaredByBothHalvesAsync();

        var disagreements = new List<string>();

        foreach (var e in fixture.GetProperty("exchanges").EnumerateArray())
        {
            var name = e.GetProperty("name").GetString()!;
            Compare(disagreements, "exchange " + name,
                e.GetProperty("declaredBy").GetString()!, recorder.Exchanges[name].By);
        }
        foreach (var q in fixture.GetProperty("queues").EnumerateArray())
        {
            var name = q.GetProperty("name").GetString()!;
            Compare(disagreements, "queue " + name,
                q.GetProperty("declaredBy").GetString()!, recorder.Queues[name].By);
        }
        foreach (var b in fixture.GetProperty("bindings").EnumerateArray())
        {
            var key = Key(
                b.GetProperty("queue").GetString()!,
                b.GetProperty("exchange").GetString()!,
                b.GetProperty("routingKey").GetString()!);
            Compare(disagreements, "binding " + key,
                b.GetProperty("declaredBy").GetString()!, recorder.Bindings[key]);
        }

        // Five entries, one difference, and it is about when rather than what. Java's
        // RetryTopology.declare() declares acemq.dlx, the dead-letter queue and the
        // parking queue when the consumer starts, so the fixture records them as
        // declared by both halves. This library declares exactly the same three
        // things, with the same types, durability and bindings — but on the settle
        // path, the first time a message is actually dead-lettered or parked, which is
        // asserted in
        // TheConsumerDeclaresTheDeadLetterQueuesWhenItFirstNeedsThemRatherThanAtStartUp.
        //
        // The end state on a broker is identical. The window in between is not: a
        // Java consumer leaves the two queues visible in the management UI from the
        // moment it connects, and a .NET one leaves them absent until something first
        // fails. Worth knowing before somebody writes an alert on their existence.
        Assert.Equal(
            new[]
            {
                "exchange acemq.dlx: fixture says both, here topology",
                "queue orders.new.dlq: fixture says both, here topology",
                "queue orders.new.parked: fixture says both, here topology",
                "binding orders.new.dlq|acemq.dlx|orders.new.dlq: fixture says both, here topology",
                "binding orders.new.parked|acemq.dlx|orders.new.parked: fixture says both, here topology",
            },
            disagreements);
    }

    private static void Compare(List<string> into, string what, string fixtureSays, string here)
    {
        if (fixtureSays != here) into.Add($"{what}: fixture says {fixtureSays}, here {here}");
    }

    [Fact]
    public async Task TheConsumerDeclaresTheDeadLetterQueuesWhenItFirstNeedsThemRatherThanAtStartUp()
    {
        var url = "memory://" + Guid.NewGuid().ToString("N");
        using var mq = await AceMqConnection.ConnectAsync(url);
        var queue = "orders" + Guid.NewGuid().ToString("N").Substring(0, 8);
        await mq.DeclareQueueAsync(queue);

        using var consumer = await mq.ConsumeAsync<string>(
            queue,
            ConsumerOptions.Defaults().WithRetry(RetryPolicy.Fixed(2, TimeSpan.FromSeconds(30))),
            _ => Task.FromResult(Ack.Park("nothing can be done with this")));

        // The rung is there from the moment the consumer started, because a rung that
        // does not exist drops the retry silently.
        Assert.True(await mq.QueueExistsAsync(Naming.RetryQueue(queue, TimeSpan.FromSeconds(30))));

        // The parking queue is not, which is where this library and Java differ.
        Assert.False(await mq.QueueExistsAsync(Naming.ParkedQueue(queue)));

        await mq.Publisher<string>("", queue).SendAsync("park me");

        var deadline = DateTime.UtcNow.AddSeconds(10);
        while (DateTime.UtcNow < deadline && !await mq.QueueExistsAsync(Naming.ParkedQueue(queue)))
        {
            await Task.Delay(10);
        }

        // And it is there once it is needed, with the message in it, so nothing is
        // lost by the wait — only the ability to see the queue before anything failed.
        Assert.True(await mq.QueueExistsAsync(Naming.ParkedQueue(queue)));
        Assert.Equal(1, await mq.MessageCountAsync(Naming.ParkedQueue(queue)));
    }

