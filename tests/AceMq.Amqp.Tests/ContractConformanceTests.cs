    /// <summary>
    /// The rung-name rule written a second time, the obvious way.
    /// </summary>
    /// <remarks>
    /// Deliberately not a call into <see cref="Naming"/>. Two readings of the same
    /// method agree with each other by construction; two implementations of the same
    /// rule only agree if the rule is what both of them implement.
    /// </remarks>
    private static string RenderDelayTheObviousWay(long millis)
    {
        if (millis <= 0) return "0s";
        if (millis % 3_600_000 == 0) return Digits(millis / 3_600_000) + "h";
        if (millis % 60_000 == 0) return Digits(millis / 60_000) + "m";
        if (millis % 1_000 == 0) return Digits(millis / 1_000) + "s";
        return Digits(millis) + "ms";
    }

    private static string Digits(long value) => value.ToString(CultureInfo.InvariantCulture);

    [Fact]
    public void TheDeadLetterAndParkedQueuesAreNamedTheWayEveryLibraryNamesThem()
    {
        var fixture = Section("naming");
        var queue = fixture.GetProperty("queue").GetString()!;
        Assert.Equal(Queue, queue);

        Assert.Equal(fixture.GetProperty("deadLetterQueue").GetString(), Naming.DeadLetterQueue(queue));
        Assert.Equal(fixture.GetProperty("parkedQueue").GetString(), Naming.ParkedQueue(queue));

        // And the same two names derived from the suffixes rather than from the
        // method, so that a change to both at once still fails.
        Assert.Equal(queue + ".dlq", Naming.DeadLetterQueue(queue));
        Assert.Equal(queue + ".parked", Naming.ParkedQueue(queue));
        Assert.Equal(".dlq", Naming.DeadLetterSuffix);
        Assert.Equal(".parked", Naming.ParkedSuffix);

        Assert.Equal(Naming.DeadLetterExchange, Fixture().GetProperty("deadLetterExchange").GetString());
        Assert.Equal(RetryLadder.RetryExchange, Fixture().GetProperty("retryExchange").GetString());
    }

    [Fact]
    public void EveryRungQueueIsNamedForItsDelay()
    {
        var rows = 0;
        foreach (var row in Section("naming").GetProperty("retryQueues").EnumerateArray())
        {
            rows++;
            var millis = row.GetProperty("delayMillis").GetInt64();
            var expected = row.GetProperty("queue").GetString();

            Assert.Equal(expected, Naming.RetryQueue(Queue, Millis(millis)));

            // The second implementation. If both this and Naming.Describe were wrong
            // in the same way the fixture would still catch it; this catches the case
            // where the fixture is wrong in the same way as Naming.Describe.
            Assert.Equal(expected, Queue + ".retry." + RenderDelayTheObviousWay(millis));
        }

        Assert.Equal(6, rows);
    }

    [Fact]
    public void ThisLibraryRendersASubSecondRungTheWayJavaDoesAndNotTheWayGoPythonAndRubyDo()
    {
        // The one disagreement the fixture records rather than settles. Java renders
        // 500ms as orders.new.retry.500ms; Go, Python and Ruby divide by a thousand
        // and render orders.new.retry.0s. This library is on Java's side, which its
        // own Naming.Describe already says in a comment and which is asserted here so
        // that it is a fact rather than a claim.
        //
        // Not resolved here, and not resolvable here: the fixture is shared, and the
        // three libraries on the other side would have to move at the same time.
        var disagreement = Section("naming").GetProperty("subSecondDisagreement").GetString()!;
        Assert.Contains("orders.new.retry.500ms", disagreement);
        Assert.Contains("orders.new.retry.0s", disagreement);

        var name = Naming.RetryQueue(Queue, TimeSpan.FromMilliseconds(500));
        Assert.Equal("orders.new.retry.500ms", name);
        Assert.NotEqual("orders.new.retry.0s", name);
        Assert.Equal("500ms", Naming.Describe(TimeSpan.FromMilliseconds(500)));

        // Unreachable through the default threshold, which is what keeps it a
        // difference on paper. A rung only exists at or above thirty seconds.
        Assert.True(
            RetryLadder.For(Queue, RetryPolicy.Fixed(3, TimeSpan.FromMilliseconds(500))).IsEmpty);
    }

    // ---- rungArguments ---------------------------------------------------

    [Fact]
    public void EveryRungCarriesExactlyThreeArgumentsAndTheSameThree()
    {
        var rows = 0;
        foreach (var row in Section("rungArguments").EnumerateArray())
        {
            rows++;
            var millis = row.GetProperty("delayMillis").GetInt64();
            var expected = row.GetProperty("arguments");

            Assert.Equal(row.GetProperty("queue").GetString(), Naming.RetryQueue(Queue, Millis(millis)));

            var actual = RetryLadder.ArgumentsFor(Queue, Millis(millis));

            // The count as well as the values. A fourth argument — a length limit, an
            // overflow policy, anything somebody adds locally — is a
            // PRECONDITION_FAILED for the second service that declares this queue,
            // and it would slip past an assertion that only checked the three it
            // knew about.
            Assert.Equal(3, actual.Count);
            Assert.Equal(
                expected.EnumerateObject().Select(p => p.Name).OrderBy(n => n, StringComparer.Ordinal),
                actual.Keys.OrderBy(n => n, StringComparer.Ordinal));

            Assert.Equal(millis, Convert.ToInt64(actual[RetryLadder.MessageTtlArgument]));
            Assert.Equal(
                expected.GetProperty("x-message-ttl").GetInt64(),
                Convert.ToInt64(actual[RetryLadder.MessageTtlArgument]));
            Assert.Equal(
                expected.GetProperty("x-dead-letter-exchange").GetString(),
                actual[RetryLadder.DeadLetterExchangeArgument]);
            Assert.Equal(
                expected.GetProperty("x-dead-letter-routing-key").GetString(),
                actual[RetryLadder.DeadLetterRoutingKeyArgument]);

            // The routing key is the source queue, not the rung. A rung that sent its
            // expiries back to itself would loop forever.
            Assert.Equal(Queue, actual[RetryLadder.DeadLetterRoutingKeyArgument]);
        }

        Assert.Equal(6, rows);
    }

