using System.Globalization;
using System.Text.Json;
using AceMq.Amqp;

namespace AceMq.Amqp.Tests;

/// <summary>
/// Asserts this library against <c>fixtures/contract-fixtures.json</c>, the retry
/// schedule, queue names and topology every AceMQ library has to agree on.
/// </summary>
/// <remarks>
/// <para>
/// The fixture is generated by the Java library's own test suite and copied here byte
/// for byte; <c>../scripts/check-fixtures.sh</c> fails if any library's copy has
/// drifted by a character. Nothing in this file may edit it. When this library
/// disagrees with it, the disagreement is written down as a disagreement — a named,
/// asserted exception saying what .NET does and what the fixture says — rather than
/// smoothed away by relaxing an assertion, because four other repositories carry the
/// same bytes and a fixture that has been quietly bent to fit one of them is worse
/// than no fixture at all.
/// </para>
/// <para>
/// This is why the file exists. Java shipped <c>exponential</c> with a multiplier of
/// five and ten percent jitter for ten releases while Go, .NET, Python and Ruby all
/// doubled with twenty — <c>exponential(5, 1s, 1m)</c> gave <c>1s, 5s, 25s, 60s</c>
/// there and <c>1s, 2s, 4s, 8s</c> here — and nobody noticed for months, because every
/// library tested its own arithmetic against its own expectations and passed.
/// </para>
/// <para>
/// So the assertions here derive their expectations wherever they can rather than
/// reading a number out of the fixture and comparing it to the same number read out of
/// this library, which proves only that both can be read. The doubling is checked by
/// asserting each delay is twice its predecessor; the threshold table is recomputed
/// from the rule the fixture states in prose; the rung names are rendered a second
/// time by an obvious implementation written in this file; the jitter bounds are
/// sampled from this library and checked against the bounds, never read back.
/// </para>
/// </remarks>
public sealed class ContractConformanceTests
{
    // ---- the fixture -----------------------------------------------------

    private static JsonElement Fixture()
    {
        var path = Path.Combine(AppContext.BaseDirectory, "fixtures", "contract-fixtures.json");
        using var doc = JsonDocument.Parse(File.ReadAllText(path));
        return doc.RootElement.Clone();
    }

    private static JsonElement Section(string name) => Fixture().GetProperty(name);

    private const string Queue = "orders.new";

    private static TimeSpan Millis(long value) => TimeSpan.FromMilliseconds(value);

    private static long[] MillisOf(IEnumerable<TimeSpan> delays) =>
        delays.Select(d => (long)d.TotalMilliseconds).ToArray();

    private static long[] LongsOf(JsonElement array) =>
        array.EnumerateArray().Select(e => e.GetInt64()).ToArray();

    /// <summary>
    /// The .NET policy for a fixture schedule, built from what the fixture's
    /// <c>how</c> field says rather than from the numbers it records.
    /// </summary>
    /// <remarks>
    /// The whole point of the exercise: the fixture names a policy in prose, both
    /// libraries construct it, and the delays that come out are compared. Reading
    /// <c>scheduleMillis</c> and feeding it back in would assert nothing.
    /// </remarks>
    private static RetryPolicy PolicyNamed(string name) => name switch
    {
        "exponential-uncapped" =>
            RetryPolicy.Exponential(5, TimeSpan.FromSeconds(1), TimeSpan.FromHours(24)),
        "exponential-capped" =>
            RetryPolicy.Exponential(6, TimeSpan.FromSeconds(10), TimeSpan.FromMinutes(1)),
        "exponential-give-up-on-age" =>
            RetryPolicy.Exponential(5, TimeSpan.FromSeconds(1), TimeSpan.FromHours(24))
                .GiveUpAfter(TimeSpan.FromMinutes(2)),
        "fixed" => RetryPolicy.Fixed(4, TimeSpan.FromSeconds(30)),
        "none" => RetryPolicy.None(),
        _ => throw new InvalidOperationException($"no policy named '{name}'"),
    };

    private static JsonElement ScheduleNamed(string name)
    {
        foreach (var entry in Section("retrySchedules").EnumerateArray())
        {
            if (entry.GetProperty("name").GetString() == name) return entry;
        }
        throw new InvalidOperationException($"no fixture schedule named '{name}'");
    }

    /// <summary>
    /// Java's default age ceiling, which this library does not have.
    /// </summary>
    /// <remarks>
    /// Java's <c>RetryPolicy</c> constructs every policy with
    /// <c>Duration.ofDays(365)</c> as its maximum message age, so the fixture records
    /// a real limit of 31,536,000,000ms on every policy that was never asked to give
    /// up on age at all. This library — and, per its own comment, the Python and Ruby
    /// ones — use zero as "never", so a message that is exactly a year old is still
    /// retried here and dead-lettered there. See
    /// <see cref="EveryRetryDecisionMatchesExceptTheAgeCeilingOnlyJavaApplies"/>.
    /// </remarks>
    private const long JavaDefaultMaxMessageAgeMillis = 31_536_000_000L;

    // ---- retrySchedules --------------------------------------------------

    [Theory]
    [InlineData("exponential-uncapped")]
    [InlineData("exponential-capped")]
    [InlineData("exponential-give-up-on-age")]
    [InlineData("fixed")]
    [InlineData("none")]
    public void EveryNamedPolicyProducesTheScheduleTheFixtureRecords(string name)
    {
        var fixture = ScheduleNamed(name);
        var policy = PolicyNamed(name);

        Assert.Equal(fixture.GetProperty("maxAttempts").GetInt32(), policy.MaxAttempts);
        Assert.Equal(fixture.GetProperty("jitterFactor").GetDouble(), policy.JitterFactor);
        Assert.Equal(
            fixture.GetProperty("brokerWaitThresholdMillis").GetInt64(),
            (long)policy.BrokerWaitThreshold.TotalMilliseconds);

        // The delays themselves. A library that agrees about the parameters and
        // disagrees about the arithmetic is the failure this fixture was built for.
        Assert.Equal(
            LongsOf(fixture.GetProperty("scheduleMillis")),
            MillisOf(policy.Schedule()));
    }

    [Theory]
    [InlineData("exponential-uncapped")]
    [InlineData("exponential-capped")]
    [InlineData("exponential-give-up-on-age")]
    [InlineData("fixed")]
    [InlineData("none")]
    public void EveryNamedPolicyNeedsTheRungQueuesTheFixtureRecords(string name)
    {
        // The rungs are the queues two services declare independently, so a policy
        // that needs a different set of them in one language is a PRECONDITION_FAILED
        // waiting for the second service to start.
        Assert.Equal(
            LongsOf(ScheduleNamed(name).GetProperty("brokerRungDelaysMillis")),
            MillisOf(PolicyNamed(name).BrokerRungs()));
    }

    [Fact]
    public void TheExponentialSchedulesActuallyDoubleUntilTheyReachTheirCeiling()
    {
        // Derived rather than read. Comparing the fixture's numbers to this library's
        // numbers proves they match; asserting that each is twice the one before it
        // proves the multiplier is two, which is the thing Java got wrong for ten
        // releases while every library's own tests passed.
        foreach (var (name, ceilingMillis) in new[]
                 {
                     ("exponential-uncapped", 24L * 60 * 60 * 1000),
                     ("exponential-capped", 60L * 1000),
                 })
        {
            var schedule = MillisOf(PolicyNamed(name).Schedule());
            Assert.Equal(LongsOf(ScheduleNamed(name).GetProperty("scheduleMillis")), schedule);

            for (var i = 1; i < schedule.Length; i++)
            {
                var doubled = schedule[i - 1] * 2;
                Assert.True(
                    schedule[i] == doubled || (schedule[i] == ceilingMillis && doubled > ceilingMillis),
                    $"{name}[{i}] is {schedule[i]}ms; twice its predecessor is {doubled}ms and the "
                    + $"ceiling is {ceilingMillis}ms");
            }
        }
    }

    [Theory]
    [InlineData("exponential-uncapped")]
    [InlineData("exponential-capped")]
    [InlineData("exponential-give-up-on-age")]
    [InlineData("fixed")]
    [InlineData("none")]
    public void EveryRetryDecisionMatchesExceptTheAgeCeilingOnlyJavaApplies(string name)
    {
        var fixture = ScheduleNamed(name);
        var policy = PolicyNamed(name);
        var fixtureLimit = fixture.GetProperty("maxMessageAgeMillis").GetInt64();

        // Every row where this library and the fixture answer differently, collected
        // rather than asserted one at a time, so that the set of disagreements can be
        // pinned exactly. A new disagreement fails here; so does one of these
        // disappearing, which is what happens when somebody resolves it.
        var disagreements = new List<string>();
        var rows = 0;

        foreach (var decision in fixture.GetProperty("decisions").EnumerateArray())
        {
            rows++;
            var attempt = decision.GetProperty("attempt").GetInt32();
            var age = decision.GetProperty("messageAgeMillis").GetInt64();
            var fixtureRetries = decision.GetProperty("retries").GetBoolean();
            var here = policy.NextWait(attempt, Millis(age)) != null;

            if (here != fixtureRetries)
            {
                disagreements.Add(
                    $"attempt={attempt} age={age}ms fixture={fixtureRetries} dotnet={here}");
            }
        }

        Assert.True(rows > 0, "the fixture recorded no decisions for " + name);

        // The only disagreement, and only for the policies that were never given an
        // age limit at all: Java gives every policy a default ceiling of 365 days, so
        // it stops retrying a message that has reached exactly that age. This library
        // treats "no limit" as no limit, and keeps going. The two rows are the ones
        // the fixture generator produced by walking to the limit it believed in.
        var expected = new List<string>();
        if (fixtureLimit == JavaDefaultMaxMessageAgeMillis && policy.MaxAttempts > 1)
        {
            expected.Add(
                $"attempt=1 age={JavaDefaultMaxMessageAgeMillis}ms fixture=False dotnet=True");
            expected.Add(
                $"attempt={policy.MaxAttempts - 1} age={JavaDefaultMaxMessageAgeMillis}ms "
                + "fixture=False dotnet=True");
        }

        Assert.Equal(expected, disagreements);
    }

    [Fact]
    public void ThisLibraryHasNoDefaultAgeCeilingWhereJavaHasOneOfAYear()
    {
        // The disagreement above, stated once as the property it is rather than as a
        // list of rows. Zero means never here, in Python and in Ruby; Java has no way
        // to say never and uses 365 days for it, which then leaves the Java library as
        // the only one of the five that will refuse to retry a very old message.
        Assert.Equal(TimeSpan.Zero, RetryPolicy.Exponential(5, TimeSpan.FromSeconds(1)).MaxMessageAge);
        Assert.Equal(TimeSpan.Zero, RetryPolicy.Fixed(4, TimeSpan.FromSeconds(30)).MaxMessageAge);
        Assert.Equal(TimeSpan.Zero, RetryPolicy.None().MaxMessageAge);

        foreach (var schedule in Section("retrySchedules").EnumerateArray())
        {
            var recorded = schedule.GetProperty("maxMessageAgeMillis").GetInt64();
            var asked = schedule.GetProperty("name").GetString() == "exponential-give-up-on-age";
            Assert.Equal(asked ? 120_000L : JavaDefaultMaxMessageAgeMillis, recorded);
        }

        // Where an age limit was actually asked for, the two agree exactly.
        var giveUp = PolicyNamed("exponential-give-up-on-age");
        Assert.Equal(TimeSpan.FromMinutes(2), giveUp.MaxMessageAge);
        Assert.NotNull(giveUp.NextWait(1, Millis(119_999)));
        Assert.Null(giveUp.NextWait(1, Millis(120_000)));
    }

    // ---- jitter ----------------------------------------------------------

    [Fact]
    public void JitterMovesAConsumerWaitBothWaysAndStaysInsideTheMultipliers()
    {
        var fixture = Section("jitter");
        var factor = fixture.GetProperty("factor").GetDouble();

        // The fixture's own two multipliers have to be the factor either side of one,
        // or the section disagrees with itself before any library is consulted.
        Assert.True(fixture.GetProperty("appliesInBothDirections").GetBoolean());
        Assert.Equal(1 - factor, fixture.GetProperty("minMultiplier").GetDouble(), 9);
        Assert.Equal(1 + factor, fixture.GetProperty("maxMultiplier").GetDouble(), 9);
        Assert.True(fixture.GetProperty("appliesToConsumerWaits").GetBoolean());
        Assert.False(fixture.GetProperty("appliesToBrokerWaits").GetBoolean());

        var policy = PolicyNamed(fixture.GetProperty("policy").GetString()!);
        Assert.Equal(factor, policy.JitterFactor);

        // Sampled from this library rather than read back out of the file. The bounds
        // are the claim; twenty thousand draws are what turns the claim into evidence.
        var baseDelay = policy.Schedule()[0];
        var low = long.MaxValue;
        var high = long.MinValue;
        for (var i = 0; i < 20_000; i++)
        {
            var wait = policy.NextWait(1, TimeSpan.Zero);
            Assert.NotNull(wait);
            Assert.False(wait!.InBroker, "a one-second wait belongs in the consumer");
            var sampled = (long)wait.Delay.TotalMilliseconds;
            low = Math.Min(low, sampled);
            high = Math.Max(high, sampled);
        }

        var baseMillis = (long)baseDelay.TotalMilliseconds;
        Assert.True(low < baseMillis, $"jitter never shortened the delay: low was {low}ms");
        Assert.True(high > baseMillis, $"jitter never lengthened the delay: high was {high}ms");
        Assert.True(
            low >= baseMillis * (1 - factor),
            $"jitter went below its own bound: {low}ms against {baseMillis * (1 - factor)}ms");
        Assert.True(
            high <= baseMillis * (1 + factor),
            $"jitter went above its own bound: {high}ms against {baseMillis * (1 + factor)}ms");

        // And never below the floor, which is the other half of the fixture's claim.
        var floor = fixture.GetProperty("flooredAtMillis").GetInt64();
        Assert.True(low >= floor, $"a consumer wait of {low}ms fell below the floor of {floor}ms");
    }

    [Fact]
    public void AWaitHeldInTheBrokerIsNeverJittered()
    {
        var factor = Section("jitter").GetProperty("factor").GetDouble();

        // A rung queue's time-to-live is fixed when it is declared, so a moved delay
        // names a queue nobody created. This is the assertion that a library which
        // jitters uniformly would fail.
        var policy = RetryPolicy.Fixed(2, TimeSpan.FromMinutes(1)).WithJitter(factor);
        for (var i = 0; i < 1_000; i++)
        {
            var wait = policy.NextWait(1, TimeSpan.Zero);
            Assert.NotNull(wait);
            Assert.True(wait!.InBroker);
            Assert.Equal(60_000d, wait.Delay.TotalMilliseconds);
        }
    }

    [Fact]
    public void TheJitterFloorIsWholeMillisecondsInJavaAndSubMillisecondHere()
    {
        // The fixture's flooredAtMillis of 1 is not a constant Java declares; it is
        // the smallest wait its generator saw from fixed(2, 1ms).withJitter(1.0), and
        // it is 1 because Java's applyJitter ends in Math.max(1, ...). This library
        // multiplies a TimeSpan and floors at zero, so the same policy produces waits
        // of a fraction of a millisecond.
        //
        // It costs nothing — the difference is between sleeping 0.3ms and sleeping
        // 1ms, on a policy nobody writes — but it is a difference, and the fixture
        // states its floor as a rule rather than as an observation, so it is asserted
        // here as what this library actually does rather than left to be discovered.
        var floor = Section("jitter").GetProperty("flooredAtMillis").GetInt64();
        Assert.Equal(1L, floor);

        var tiny = RetryPolicy.Fixed(2, TimeSpan.FromMilliseconds(1)).WithJitter(1.0);
        var lowest = double.MaxValue;
        for (var i = 0; i < 5_000; i++)
        {
            var wait = tiny.NextWait(1, TimeSpan.Zero);
            Assert.NotNull(wait);
            Assert.False(wait!.InBroker);
            Assert.True(wait.Delay >= TimeSpan.Zero, "a delay is never negative");
            lowest = Math.Min(lowest, wait.Delay.TotalMilliseconds);
        }

        Assert.True(
            lowest < floor,
            $"this library floored a jittered millisecond at {lowest}ms; Java floors it at {floor}ms, "
            + "and if that has changed here the fixture and this comment both need revisiting");

        // The floor the fixture states does hold for every delay the fixture's own
        // jitter section is about, which is why this is a latent difference rather
        // than a live one: a rung is only reached at or above the broker-wait
        // threshold, and a consumer wait of a millisecond is not something a policy in
        // this repository produces.
        var real = PolicyNamed("exponential-uncapped");
        for (var i = 0; i < 1_000; i++)
        {
            Assert.True(real.NextWait(1, TimeSpan.Zero)!.Delay.TotalMilliseconds >= floor);
        }
    }

