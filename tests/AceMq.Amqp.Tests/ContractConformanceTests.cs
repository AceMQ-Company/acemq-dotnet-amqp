    /// <summary>
    /// A connection that records declarations instead of making them, so that what
    /// the consumer's half of the topology declares can be compared without a broker.
    /// </summary>
    /// <remarks>
    /// The counterpart to the <c>Recorder</c> inside Java's fixture generator. Every
    /// method that is not a declaration throws: this exists to be declared at, and a
    /// test that reached one of them would be testing something else.
    /// </remarks>
    private sealed class Recorder : ITransportConnection
    {
        public string By { get; set; } = "topology";

        public Dictionary<string, (string Type, bool Durable, string By)> Exchanges { get; } =
            new Dictionary<string, (string, bool, string)>(StringComparer.Ordinal);

        public Dictionary<string, (QueueType Type, bool Durable,
            IReadOnlyDictionary<string, object> Arguments, string By)> Queues { get; } =
            new Dictionary<string, (QueueType, bool, IReadOnlyDictionary<string, object>, string)>(
                StringComparer.Ordinal);

        public Dictionary<string, string> Bindings { get; } =
            new Dictionary<string, string>(StringComparer.Ordinal);

        public void Exchange(string name, string type, bool durable, string by)
        {
            // "both" rather than a last-writer-wins: a name declared by the
            // application and by the consumer is exactly what the fixture's
            // declaredBy is for.
            if (Exchanges.TryGetValue(name, out var seen) && seen.By != by)
            {
                Exchanges[name] = (seen.Type, seen.Durable, "both");
                return;
            }
            Exchanges[name] = (type, durable, by);
        }

        public void Queue(
            string name, QueueType type, bool durable,
            IReadOnlyDictionary<string, object> arguments, string by)
        {
            if (Queues.TryGetValue(name, out var seen) && seen.By != by)
            {
                Queues[name] = (seen.Type, seen.Durable, seen.Arguments, "both");
                return;
            }
            Queues[name] = (type, durable, arguments, by);
        }

        public void Binding(string queue, string exchange, string routingKey, string by)
        {
            var key = Key(queue, exchange, routingKey);
            if (Bindings.TryGetValue(key, out var seen) && seen != by)
            {
                Bindings[key] = "both";
                return;
            }
            Bindings[key] = by;
        }

        public Task DeclareExchangeAsync(
            string name, string type, bool durable, CancellationToken cancellationToken)
        {
            Exchange(name, type, durable, By);
            return Task.CompletedTask;
        }

        public Task DeclareQueueAsync(
            string name, QueueType type, bool durable,
            IReadOnlyDictionary<string, object>? arguments, CancellationToken cancellationToken)
        {
            Queue(name, type, durable, arguments ?? new Dictionary<string, object>(), By);
            return Task.CompletedTask;
        }

        public Task BindQueueAsync(
            string queue, string exchange, string routingKey, CancellationToken cancellationToken)
        {
            Binding(queue, exchange, routingKey, By);
            return Task.CompletedTask;
        }

        private static Exception OnlyDeclarations() =>
            new NotSupportedException("the recorder only records declarations");

        public Task<ConfirmResult> SendAsync(OutboundMessage message, CancellationToken cancellationToken) =>
            throw OnlyDeclarations();

        public Task<ISubscription> SubscribeAsync(
            string queue, int prefetch, IReadOnlyDictionary<string, object>? arguments,
            Func<InboundDelivery, Task<Ack>> handler, CancellationToken cancellationToken) =>
            throw OnlyDeclarations();

        public Task<InboundDelivery?> ReceiveAsync(
            string queue, TimeSpan timeout, CancellationToken cancellationToken) =>
            throw OnlyDeclarations();

        public Task<IPulledDelivery?> PullAsync(
            string queue, TimeSpan timeout, CancellationToken cancellationToken) =>
            throw OnlyDeclarations();

        public Task<long> MessageCountAsync(string queue, CancellationToken cancellationToken) =>
            throw OnlyDeclarations();

        public Task DeleteQueueAsync(string name, CancellationToken cancellationToken) =>
            throw OnlyDeclarations();

        public Task DeleteExchangeAsync(string name, CancellationToken cancellationToken) =>
            throw OnlyDeclarations();

        public Task<bool> QueueExistsAsync(string name, CancellationToken cancellationToken) =>
            Task.FromResult(Queues.ContainsKey(name));

        public Task<QueueCheck> CheckQueueAsync(
            string name, QueueType type, bool durable,
            IReadOnlyDictionary<string, object>? arguments, CancellationToken cancellationToken) =>
            throw OnlyDeclarations();

        public bool IsOpen => true;

        public bool IsBlocked => false;

        public string? BlockedReason => null;

        public void Dispose()
        {
        }
    }
